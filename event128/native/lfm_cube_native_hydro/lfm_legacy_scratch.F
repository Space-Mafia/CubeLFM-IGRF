C Runtime owner for the two historical scratch COMMON overlays.  The old
C numerical routines keep their original declarations; this unit only supplies
C one sufficiently large backing store now that P++ no longer owns memory.
      SUBROUTINE LFM_LEGACY_SCRATCH_READY
#include "param.inc"
      INTEGER PAD_I,PAD_J,SCRACH_WORDS,SCRCH1_WORDS,BZZ_WORDS
      INTEGER METRIC_WORDS
      INTEGER OWNER_WORDS
      PARAMETER (PAD_I=LIHIGH-LLOW+1,PAD_J=LJHIGH-LLOW+1)
      PARAMETER (SCRACH_WORDS=3*LIP4*LJP4+59*LIP1*LJP1+
     $ 4*LI*LJ+10*LIP2*LJP2+2*PAD_I*PAD_J)
      PARAMETER (SCRCH1_WORDS=4*LIP3*LJP3+LIP2*LJP2+
     $ 4*LIP1*LJP1)
      PARAMETER (BZZ_WORDS=NI*NJ*NK+3*NIP1*NJP1*NKP1+6*NK)
      PARAMETER (METRIC_WORDS=9*(NI+NO)*(NJ+NO)*(NK+NO))
      PARAMETER (OWNER_WORDS=MAX(SCRACH_WORDS,BZZ_WORDS,METRIC_WORDS))
      REAL SCRACH_RAW(OWNER_WORDS),SCRCH1_RAW(SCRCH1_WORDS)
      COMMON /SCRACH/ SCRACH_RAW
      COMMON /SCRCH1/ SCRCH1_RAW
      SAVE /SCRACH/,/SCRCH1/
      RETURN
      END

      BLOCK DATA LFM_LEGACY_SCRATCH_OWNER
#include "param.inc"
      INTEGER PAD_I,PAD_J,SCRACH_WORDS,SCRCH1_WORDS,BZZ_WORDS
      INTEGER METRIC_WORDS
      INTEGER OWNER_WORDS
      PARAMETER (PAD_I=LIHIGH-LLOW+1,PAD_J=LJHIGH-LLOW+1)
      PARAMETER (SCRACH_WORDS=3*LIP4*LJP4+59*LIP1*LJP1+
     $ 4*LI*LJ+10*LIP2*LJP2+2*PAD_I*PAD_J)
      PARAMETER (SCRCH1_WORDS=4*LIP3*LJP3+LIP2*LJP2+
     $ 4*LIP1*LJP1)
      PARAMETER (BZZ_WORDS=NI*NJ*NK+3*NIP1*NJP1*NKP1+6*NK)
      PARAMETER (METRIC_WORDS=9*(NI+NO)*(NJ+NO)*(NK+NO))
      PARAMETER (OWNER_WORDS=MAX(SCRACH_WORDS,BZZ_WORDS,METRIC_WORDS))
      REAL SCRACH_RAW(OWNER_WORDS),SCRCH1_RAW(SCRCH1_WORDS)
      COMMON /SCRACH/ SCRACH_RAW
      COMMON /SCRCH1/ SCRCH1_RAW
      DATA SCRACH_RAW /OWNER_WORDS*0.0/
      DATA SCRCH1_RAW /SCRCH1_WORDS*0.0/
      END
